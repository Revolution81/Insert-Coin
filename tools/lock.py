#!/usr/bin/env python3
"""
Write requirements.lock: every Python package the device installs, pinned
to an exact version and to the SHA-256 of every file PyPI has for that
version (so the same lock works on any Python/CPU).

    python3 tools/lock.py            # rewrite requirements.lock
    python3 tools/lock.py --check    # exit 1 if the lock doesn't match PINS

deploy/install.sh installs with `pip --require-hashes`, so pip refuses any
file whose hash isn't listed here: a tampered or swapped package on PyPI
(or on the way from it) doesn't get in. The hashes are what PyPI served on
the day this was run; review the diff when you bump a version.

Not from PyPI at all (apt, signed by Debian/Raspberry Pi): python3-evdev,
python3-picamera2, setuptools/wheel (to build embit's source package
without downloading build tools).
"""
from __future__ import annotations

import json
import os
import sys
import urllib.request

# The full set, including dependencies of dependencies. Tested versions.
PINS = {
    "pillow": "12.3.0",
    "qrcode": "8.2",
    "embit": "0.8.0",                 # source only: pure Python
    "argon2-cffi": "25.1.0",
    "argon2-cffi-bindings": "26.1.0",
    "cffi": "2.1.1",
    "pycparser": "3.0",
    "cryptography": "50.0.1",
    "pyzbar": "0.1.9",
    "shamir-mnemonic": "0.3.0",
}
SOURCE_OK = {"embit"}                 # everything else: wheels only
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LOCK = os.path.join(ROOT, "requirements.lock")


def files(name: str, version: str) -> list[tuple[str, str]]:
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    with urllib.request.urlopen(url, timeout=30) as r:
        data = json.load(r)
    out = []
    for f in data["urls"]:
        if f.get("yanked"):
            continue
        wheel = f["packagetype"] == "bdist_wheel"
        if wheel or name in SOURCE_OK:
            out.append((f["filename"], f["digests"]["sha256"]))
    if not out:
        raise SystemExit(f"{name}=={version}: no usable files on PyPI")
    return sorted(out)


def render() -> str:
    lines = ["# Generated by tools/lock.py. Don't edit by hand.",
             "# pip install --require-hashes --no-deps -r requirements.lock", ""]
    for name in sorted(PINS):
        fs = files(name, PINS[name])
        lines.append(f"{name}=={PINS[name]} \\")
        for i, (fn, sha) in enumerate(fs):
            end = " \\" if i < len(fs) - 1 else ""
            lines.append(f"    --hash=sha256:{sha}{end}  # {fn}" if not end
                         else f"    --hash=sha256:{sha} \\")
        lines.append("")
    return "\n".join(lines)


def parse(text: str) -> dict[str, tuple[str, set[str]]]:
    """name -> (version, {sha256...}) from a lock file."""
    out, cur = {}, None
    for raw in text.splitlines():
        line = raw.split("#")[0].strip().rstrip("\\").strip()
        if not line:
            continue
        if line.startswith("--hash=sha256:"):
            out[cur][1].add(line.split(":", 1)[1])
        elif "==" in line:
            cur, ver = line.split("==")
            out[cur] = (ver, set())
    return out


def main():
    if "--check" in sys.argv:
        with open(LOCK) as f:
            have = parse(f.read())
        want = {n: v for n, v in PINS.items()}
        got = {n: v for n, (v, _) in have.items()}
        if want != got or any(not h for _, h in have.values()):
            print("requirements.lock doesn't match PINS: run tools/lock.py")
            raise SystemExit(1)
        print(f"ok: {len(have)} packages, {sum(len(h) for _, h in have.values())} hashes")
        return
    text = render()
    with open(LOCK, "w") as f:
        f.write(text)
    print(f"wrote {LOCK}")


if __name__ == "__main__":
    main()
